import os
import time
import glob
import shutil
from playwright.sync_api import sync_playwright

def record_agent_demo():
    video_dir = os.path.abspath("demo_video_temp")
    if os.path.exists(video_dir):
        shutil.rmtree(video_dir)
    os.makedirs(video_dir, exist_ok=True)

    target_url = "http://localhost:8080"
    print(f"Starting Playwright demo recording for AI Concierge at {target_url}...")

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(
            viewport={"width": 1280, "height": 720},
            record_video_dir=video_dir,
            record_video_size={"width": 1280, "height": 720}
        )
        page = context.new_page()
        page.goto(target_url, wait_until="networkidle")
        time.sleep(2.5)

        # 1. Click the AI Concierge button in header navigation
        print("1. Clicking AI Concierge button...")
        concierge_btn = page.query_selector("#btnToggleConcierge") or page.query_selector("button:has-text('AI Concierge')")
        if concierge_btn:
            concierge_btn.click()
            time.sleep(2)

        # 2. First Prompt: Ask AI Concierge for a recipe
        print("2. Sending Prompt 1: Asking for a recipe...")
        chat_input = page.query_selector("input#input") or page.query_selector("#chat-input") or page.query_selector("input[type='text']")
        send_btn = page.query_selector("form#form button") or page.query_selector("#chat-send-btn")

        prompt_1 = "Hi! Can you give me a recipe for Quinoa Mediterranean Power Bowl for 4 people with ingredients and instructions?"
        if chat_input:
            chat_input.fill(prompt_1)
            time.sleep(1)
            if send_btn:
                send_btn.click()
            else:
                chat_input.press("Enter")
            
            # Wait for AI agent response
            time.sleep(15)

        # 3. Second Prompt: Ask for an image of the recipe after asking for the recipe
        print("3. Sending Prompt 2: Asking for an image of the recipe...")
        prompt_2 = "Generate a high-quality AI food photography image for this Quinoa Mediterranean Power Bowl recipe."
        if chat_input:
            chat_input.fill(prompt_2)
            time.sleep(1)
            if send_btn:
                send_btn.click()
            else:
                chat_input.press("Enter")
            
            # Wait for image generation tool execution
            time.sleep(25)

        # 4. Pause to display generated image and card response in chat drawer
        print("4. Final pause to showcase generated image and recipe response...")
        time.sleep(8)

        print("Closing browser context to save demo video...")
        context.close()
        browser.close()

    # Find recorded video file
    video_files = glob.glob(os.path.join(video_dir, "*.webm")) + glob.glob(os.path.join(video_dir, "*.mp4"))
    if video_files:
        recorded_path = video_files[0]
        output_path = "/config/.gemini/antigravity/brain/d56e0ac6-cc07-49e4-829a-147c1a284618/demo_video.webm"
        shutil.copy(recorded_path, output_path)
        print(f"Recorded video saved to: {output_path}")
        return output_path
    else:
        print("Error: No video file was generated by Playwright.")
        return None

if __name__ == "__main__":
    record_agent_demo()
